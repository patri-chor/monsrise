//  6. 枪口位置微调（px）—— 枪械类怪（子弹从武器尖端发出）
//  表只有两个值：
//   dx = 子弹相对武器锚点的 x 位置（本地 px；dx 随朝向翻转）。
//        默认值 = 枪口尖端（贴图从锚点到 x 端的长度），由生成脚本按动画数据算好；
